package me.tbsten.analysis.code.gen.testprocessors

/*
 * テスト用 Processor が生成するコード。KSP 版と Native 版は解析だけが違い、生成はここを共有する（ADR-027）。
 * 同じ入力から同じ文字列になることが三者差分（XD-*）の前提なので、並び順はすべてここで決める。
 */

/** 生成したいファイル 1 つ。 */
public data class TpFile(
    val packageName: String,
    val fileName: String,
    val extension: String,
    val content: String,
)

/** 生成したいリソース 1 つ。 */
public data class TpResourceFile(val relativePath: String, val content: String)

/**
 * パッケージ内での名前（ネストは `.` 区切り）。`Outer.Inner` → `Outer_Inner`。
 */
public fun flatName(nameInPackage: String): String = nameInPackage.replace('.', '_')

private fun header(tp: TpId): String = "// Generated by ${tp.displayName}. Do not edit.\n"

private fun packageLine(packageName: String): String = if (packageName.isEmpty()) "" else "package $packageName\n\n"

private fun qualified(
    packageName: String,
    nameInPackage: String,
): String = if (packageName.isEmpty()) nameInPackage else "$packageName.$nameInPackage"

/** Kotlin の文字列リテラル。 */
public fun kotlinString(value: String): String =
    buildString {
        append('"')
        value.forEach { c ->
            when (c) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '$' -> append("\\$")
                '\n' -> append("\\n")
                else -> append(c)
            }
        }
        append('"')
    }

private fun kotlinStringList(values: List<String>): String =
    if (values.isEmpty()) "emptyList()" else values.joinToString(", ", "listOf(", ")") { kotlinString(it) }

// ---- TP-Mapper ----

/** @property type 型の正規表記（[TypeNotation]）。 */
public data class MapperProperty(val name: String, val type: String)

public data class MapperModel(
    val packageName: String,
    val classNameInPackage: String,
    val properties: List<MapperProperty>,
)

public object MapperRender {
    public fun fileName(model: MapperModel): String = flatName(model.classNameInPackage) + "Mapper"

    public fun render(model: MapperModel): TpFile {
        val name = fileName(model)
        val target = qualified(model.packageName, model.classNameInPackage)
        val values =
            if (model.properties.isEmpty()) {
                "emptyMap()"
            } else {
                model.properties.joinToString(",\n", "mapOf(\n", ",\n    )") { "        ${kotlinString(it.name)} to value.${it.name}" }
            }
        val types =
            if (model.properties.isEmpty()) {
                "emptyMap()"
            } else {
                model.properties.joinToString(", ", "mapOf(", ")") { "${kotlinString(it.name)} to ${kotlinString(it.type)}" }
            }
        val content =
            header(TpId.Mapper) + packageLine(model.packageName) +
                "public object $name {\n" +
                "    public fun toMap(value: $target): Map<String, Any?> = $values\n\n" +
                "    public val propertyTypes: Map<String, String> = $types\n" +
                "}\n"
        return TpFile(model.packageName, name, "kt", content)
    }
}

// ---- TP-Registry ----

public data class RegistryModel(
    val packageName: String,
    val name: String,
    val entries: List<String>,
    val platform: String,
)

public object RegistryRender {
    public fun render(model: RegistryModel): TpFile {
        val content =
            header(TpId.Registry) + packageLine(model.packageName) +
                "public object ${model.name} {\n" +
                "    public val entries: List<String> = ${kotlinStringList(model.entries.sorted())}\n\n" +
                "    public val platform: String = ${kotlinString(model.platform)}\n" +
                "}\n"
        return TpFile(model.packageName, model.name, "kt", content)
    }
}

// ---- TP-Chain ----

/** `@Chain(depth, step, origin)` が付いたクラス 1 つ。 */
public data class ChainModel(
    val packageName: String,
    val classNameInPackage: String,
    val depth: Int,
    val step: Int,
    val origin: String,
)

public object ChainRender {
    /** depth が 0 なら次の段は作らない。 */
    public fun render(model: ChainModel): TpFile? {
        if (model.depth <= 0) return null
        val origin = model.origin.ifEmpty { flatName(model.classNameInPackage) }
        val nextStep = model.step + 1
        val name = "${origin}Chain$nextStep"
        val prev = qualified(model.packageName, model.classNameInPackage)
        val content =
            header(TpId.Chain) + packageLine(model.packageName) +
                "@${TpAnnotations.CHAIN}(depth = ${model.depth - 1}, step = $nextStep, origin = ${kotlinString(origin)})\n" +
                "public class $name(public val prev: $prev) {\n" +
                "    public val step: Int = $nextStep\n" +
                "}\n"
        return TpFile(model.packageName, name, "kt", content)
    }
}

// ---- TP-Actual ----

public data class ActualFunction(val name: String, val visibility: String)

/** 1 つのソースファイルにある `@GenerateActual expect fun` の集まり。 */
public data class ActualModel(
    val packageName: String,
    val sourceFileBaseName: String,
    val functions: List<ActualFunction>,
    val platform: String,
)

public object ActualRender {
    public fun render(model: ActualModel): TpFile {
        val name = model.sourceFileBaseName + "Actual"
        val body =
            model.functions.sortedBy { it.name }.joinToString("\n") {
                "${it.visibility} actual fun ${it.name}(): String = ${kotlinString(model.platform)}\n"
            }
        return TpFile(model.packageName, name, "kt", header(TpId.Actual) + packageLine(model.packageName) + body)
    }
}

// ---- TP-Body ----

/**
 * @property ownerInPackage メンバー関数ならクラスのパッケージ内の名前。トップレベルなら null。
 * @property callees 呼び出し先の FQN。コンストラクタは `<クラスの FQN>.<init>`。
 */
public data class BodyModel(
    val packageName: String,
    val ownerInPackage: String?,
    val functionName: String,
    val callees: List<String>,
)

public object BodyRender {
    public fun fileName(model: BodyModel): String =
        if (model.ownerInPackage == null) {
            model.functionName.replaceFirstChar { it.uppercase() } + "CallGraph"
        } else {
            flatName(model.ownerInPackage) + "_" + model.functionName + "CallGraph"
        }

    public fun render(model: BodyModel): TpFile {
        val name = fileName(model)
        val content =
            header(TpId.Body) + packageLine(model.packageName) +
                "public object $name {\n" +
                "    public val callees: List<String> = ${kotlinStringList(model.callees.distinct().sorted())}\n" +
                "}\n"
        return TpFile(model.packageName, name, "kt", content)
    }
}

