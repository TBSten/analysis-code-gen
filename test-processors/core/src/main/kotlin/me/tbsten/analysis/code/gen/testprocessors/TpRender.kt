// ---- TP-Resource ----

public data class ResourceModel(val packageName: String, val classNameInPackage: String)

public object ResourceRender {
    public const val SERVICES_PATH: String = "META-INF/services/${TpAnnotations.RESOURCE_MARKER}"

    public fun javaName(model: ResourceModel): String = flatName(model.classNameInPackage) + "Java"

    public fun javaFqn(model: ResourceModel): String = qualified(model.packageName, javaName(model))

    public fun java(model: ResourceModel): TpFile {
        val name = javaName(model)
        val pkg = if (model.packageName.isEmpty()) "" else "package ${model.packageName};\n\n"
        val content =
            header(TpId.Resource) + pkg +
                "public final class $name {\n" +
                "    public static final String NAME = ${kotlinString(qualified(model.packageName, model.classNameInPackage))};\n\n" +
                "    private $name() {\n" +
                "    }\n" +
                "}\n"
        return TpFile(model.packageName, name, "java", content)
    }

    /** 前のラウンドで作った Java クラスを Kotlin から参照する（RND-06）。 */
    public fun kotlinRef(model: ResourceModel): TpFile {
        val name = javaName(model) + "Ref"
        val content =
            header(TpId.Resource) + packageLine(model.packageName) +
                "public object $name {\n" +
                "    public val name: String = ${javaFqn(model)}.NAME\n" +
                "}\n"
        return TpFile(model.packageName, name, "kt", content)
    }

    public fun properties(model: ResourceModel): TpResourceFile {
        val fqn = qualified(model.packageName, model.classNameInPackage)
        return TpResourceFile("tp-resources/$fqn.properties", "name=$fqn\n")
    }

    /** `META-INF/services`。クラスの FQN（ネストは `$`）を辞書順に並べる。 */
    public fun services(models: List<ResourceModel>): TpResourceFile =
        TpResourceFile(
            SERVICES_PATH,
            models.map { qualified(it.packageName, it.classNameInPackage.replace('.', '$')) }.sorted().joinToString("") { "$it\n" },
        )
}

// ---- TP-Bad ----

public object BadRender {
    public fun simple(
        name: String,
        packageName: String = "me.tbsten.analysis.code.gen.tp.bad",
    ): TpFile = TpFile(packageName, name, "kt", header(TpId.Bad) + packageLine(packageName) + "public object $name\n")

    /** TP-Mapper と同じパスに置く、中身の違うファイル。 */
    public fun collide(
        packageName: String,
        classNameInPackage: String,
    ): TpFile {
        val name = flatName(classNameInPackage) + "Mapper"
        return TpFile(packageName, name, "kt", header(TpId.Bad) + packageLine(packageName) + "public object $name\n")
    }

    public const val THROW_MESSAGE: String = "TP-Bad: intentional failure (throw)"
    public const val LOG_ERROR_MESSAGE: String = "TP-Bad: intentional error (log-error)"
}

// ---- 型の表記 ----

/**
 * 型の正規表記。KSP 版と Native 版で同じ文字列にするための規則（ADR-027）。
 *
 * - クラス型: `<FQN（ネストは .）><型引数>`。typealias は展開する
 * - 型引数: `*`、`out T`、`in T`、`T`
 * - 型パラメータ: 名前だけ
 * - nullable: 末尾に `?`。解決できない型は `<error>`
 * - 関数型も `kotlin.Function1<A, R>` のようにクラス型として書く
 */
public object TypeNotation {
    public const val ERROR: String = "<error>"

    public fun classType(
        fqName: String,
        arguments: List<String>,
        nullable: Boolean,
    ): String = fqName + (if (arguments.isEmpty()) "" else arguments.joinToString(", ", "<", ">")) + (if (nullable) "?" else "")

    public fun typeParameter(
        name: String,
        nullable: Boolean,
    ): String = name + (if (nullable) "?" else "")

    public fun argument(
        variance: String?,
        type: String?,
    ): String =
        when {
            type == null -> "*"
            variance.isNullOrEmpty() -> type
            else -> "$variance $type"
        }
}

/** プラットフォーム名の正規表記（TP-Actual・TP-Registry が生成物に書く）。 */
public object PlatformNames {
    public const val COMMON: String = "common"
    public const val JVM: String = "jvm"
    public const val JS: String = "js"
    public const val WASM: String = "wasm"
    public const val NATIVE: String = "native"
    public const val UNKNOWN: String = "unknown"
}
