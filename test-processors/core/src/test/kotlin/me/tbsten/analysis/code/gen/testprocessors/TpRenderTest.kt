package me.tbsten.analysis.code.gen.testprocessors

import io.kotest.assertions.throwables.shouldThrow
import io.kotest.core.spec.style.FreeSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain

class TpRenderTest : FreeSpec({
    "TP-Mapper" - {
        "プロパティを宣言順に並べ、パッケージとファイル名がクラスに対応する" {
            val file =
                MapperRender.render(
                    MapperModel(
                        "com.example",
                        "User",
                        listOf(MapperProperty("id", "kotlin.Int"), MapperProperty("name", "kotlin.String?")),
                    ),
                )
            file.fileName shouldBe "UserMapper"
            file.content shouldBe
                """
                |// Generated by TP-Mapper. Do not edit.
                |package com.example
                |
                |public object UserMapper {
                |    public fun toMap(value: com.example.User): Map<String, Any?> = mapOf(
                |        "id" to value.id,
                |        "name" to value.name,
                |    )
                |
                |    public val propertyTypes: Map<String, String> = mapOf("id" to "kotlin.Int", "name" to "kotlin.String?")
                |}
                |
                """.trimMargin()
        }
        "ルートパッケージのネストしたクラスでは package 行を出さず _ でつなぐ" {
            val file = MapperRender.render(MapperModel("", "Outer.Inner", emptyList()))
            file.fileName shouldBe "Outer_InnerMapper"
            file.content shouldNotContain "package"
            file.content shouldContain "toMap(value: Outer.Inner): Map<String, Any?> = emptyMap()"
        }
    }

    "TP-Registry は並び順を入力に依存させない" {
        val a = RegistryRender.render(RegistryModel("p", "R", listOf("b.B", "a.A"), "jvm"))
        val b = RegistryRender.render(RegistryModel("p", "R", listOf("a.A", "b.B"), "jvm"))
        a shouldBe b
        a.content shouldContain "listOf(\"a.A\", \"b.B\")"
    }

    "TP-Chain" - {
        "depth が残っていれば次の段を作り、前の段を型として参照する" {
            val file = ChainRender.render(ChainModel("p", "Pipeline", depth = 3, step = 0, origin = ""))!!
            file.fileName shouldBe "PipelineChain1"
            file.content shouldContain "@me.tbsten.analysis.code.gen.tp.Chain(depth = 2, step = 1, origin = \"Pipeline\")"
            file.content shouldContain "public class PipelineChain1(public val prev: p.Pipeline)"
        }
        "depth 0 なら作らない" {
            ChainRender.render(ChainModel("p", "PipelineChain3", depth = 0, step = 3, origin = "Pipeline")) shouldBe null
        }
    }

    "TP-Actual は関数名順に actual を並べる" {
        val file =
            ActualRender.render(
                ActualModel("p", "Platform", listOf(ActualFunction("b", "public"), ActualFunction("a", "internal")), "jvm"),
            )
        file.fileName shouldBe "PlatformActual"
        file.content shouldContain "internal actual fun a(): String = \"jvm\"\n\npublic actual fun b(): String = \"jvm\""
    }

    "TP-Body は呼び出し先を重複なく辞書順に並べる" {
        val file = BodyRender.render(BodyModel("p", "Service", "run", listOf("p.b", "p.a", "p.b")))
        file.fileName shouldBe "Service_runCallGraph"
        file.content shouldContain "listOf(\"p.a\", \"p.b\")"
        BodyRender.fileName(BodyModel("p", null, "main", emptyList())) shouldBe "MainCallGraph"
    }

    "TP-Resource は Java・Kotlin の参照・リソースを作る" {
        val model = ResourceModel("p", "Report")
        ResourceRender.java(model).content shouldContain "public static final String NAME = \"p.Report\";"
        ResourceRender.kotlinRef(model).content shouldContain "public val name: String = p.ReportJava.NAME"
        ResourceRender.properties(model) shouldBe TpResourceFile("tp-resources/p.Report.properties", "name=p.Report\n")
        ResourceRender.services(listOf(ResourceModel("p", "B.C"), model)).content shouldBe "p.B\$C\np.Report\n"
    }

    "文字列リテラルは \$ と引用符をエスケープする" {
        kotlinString("a\"\$b") shouldBe "\"a\\\"\\\$b\""
    }

    "型の正規表記" {
        TypeNotation.classType(
            "kotlin.collections.Map",
            listOf(TypeNotation.argument(null, "kotlin.String"), TypeNotation.argument("out", "T"), TypeNotation.argument(null, null)),
            nullable = true,
        ) shouldBe "kotlin.collections.Map<kotlin.String, out T, *>?"
    }

    "オプション" - {
        "指定が無ければ TP-Bad と TP-Probe 以外が有効" {
            TpOptions(emptyMap()).enabled shouldBe TpId.defaults
        }
        "all は TP-Bad 以外の全部" {
            TpOptions(mapOf(TpOptionKeys.PROCESSORS to "all")).enabled shouldBe (TpId.entries.toSet() - TpId.Bad)
        }
        "カンマ区切りで選べ、未知の名前はエラー" {
            TpOptions(mapOf(TpOptionKeys.PROCESSORS to "mapper, Bad")).enabled shouldBe setOf(TpId.Mapper, TpId.Bad)
            shouldThrow<IllegalArgumentException> { TpOptions(mapOf(TpOptionKeys.PROCESSORS to "Nope")) }
        }
        "TP-Bad のモードと TP-Probe のログを読む" {
            val options = TpOptions(mapOf(TpOptionKeys.BAD_MODES to "throw,collide", TpOptionKeys.PROBE_LOG to "warn:w;error:e: x"))
            options.badModes shouldBe setOf(BadMode.Throw, BadMode.Collide)
            options.probeLogs shouldBe listOf(ProbeLog("warn", "w"), ProbeLog("error", "e: x"))
        }
    }

    "TP-Probe のイベントは 1 行の JSON になる" {
        val json =
            ProbeEvent(
                "process",
                "ksp",
                "1",
                round = 2,
                options = mapOf("b" to "2", "a" to "1"),
                newFiles = listOf("A\".kt"),
            ).toJson()
        json shouldNotContain "\n"
        json shouldContain "\"round\":2"
        json shouldContain "\"options\":{\"a\":\"1\",\"b\":\"2\"}"
        json shouldContain "\"newFiles\":[\"A\\\".kt\"]"
    }
})
